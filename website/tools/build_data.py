"""Regenerates website/assets/js/data.js from the app's catalogue source.

Run from the repository root:
    python3 website/tools/build_data.py

The app's Dart catalogue (lib/data/mock/mock_catalogue.dart) stays the single
source of truth, so the website and the app always show the same demo items.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "lib/data/mock/mock_catalogue.dart"
OUT = ROOT / "website/assets/js/data.js"


def strings(block, field):
    m = re.search(rf"{field}:\s*'([^']*)'", block)
    return m.group(1) if m else None


def numbers(block, field):
    m = re.search(rf"{field}:\s*([0-9.]+)", block)
    return float(m.group(1)) if m else None


def main():
    text = SOURCE.read_text(encoding="utf-8")

    disclosure = re.search(
        r"priceDisclosure =\s*'([^']*)'\s*'([^']*)'|priceDisclosure =\s*'([^']*)'",
        text,
    )
    notice = "Illustrative demo price. Not an actual Modi International quote."

    categories = []
    for block in re.findall(r"ProductCategory\((.*?)\)", text, flags=re.S):
        categories.append({
            "id": strings(block, "id"),
            "name": strings(block, "name"),
            "description": strings(block, "description"),
        })

    products = []
    for block in re.findall(r"Product\((.*?)\n    \)", text, flags=re.S):
        products.append({
            "id": strings(block, "id"),
            "name": strings(block, "name"),
            "categoryId": strings(block, "categoryId"),
            "price": numbers(block, "price"),
            "currency": strings(block, "currency") or "₹",
        })

    products = [p for p in products if p["id"]]
    categories = [c for c in categories if c["id"]]

    payload = {"notice": notice, "categories": categories, "products": products}
    OUT.write_text(
        "// Generated by website/tools/build_data.py from the app catalogue. Do not edit.\n"
        "window.MODI_DATA = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(categories)} categories, {len(products)} products")


if __name__ == "__main__":
    main()
